import { читатьНастройки, отметитьЗапуск } from './config.js';
import { сон } from './http.js';
import * as ozon from './ozon.js';
import * as wb from './wb.js';
import * as yandex from './yandex.js';

const ОБРАБОТЧИКИ = {
  'OZON продажи': ozon.продажи,
  'OZON остатки': ozon.остатки,
  'WB продажи': wb.продажи,
  'WB остатки': wb.остатки,
  'Яндекс продажи': yandex.продажи,
  'Яндекс остатки': yandex.остатки,
};

const лог = (...ч) => console.log(new Date().toISOString(), ...ч);

// «Последний запуск» отметитьЗапуск пишет по Москве, а сервер живёт в UTC.
// Москва — UTC+3 круглый год, перевода часов нет с 2014-го.
const МСК_СМЕЩЕНИЕ = 3 * 3600 * 1000;

// Ячейку пишем через USER_ENTERED, поэтому Sheets хранит её как дату-время и отдаёт
// обратно в своём формате отображения — ведущие нули в дне, месяце и часе не гарантированы
// («26.08.2026, 8:11:32»). Поэтому допускаем одну или две цифры везде, где Sheets их режет.
const ОТМЕТКА = /(\d{1,2})\.(\d{1,2})\.(\d{4}),?\s+(\d{1,2}):(\d{2})/;

/** Пора ли запускать: прошло ли «каждые N минут» с прошлого раза. */
function пора(задача) {
  if (!задача.последний) return true;

  const м = String(задача.последний).match(ОТМЕТКА);
  if (!м) {
    // не молчим: иначе неразобранная отметка тихо превращается в запуск каждую минуту
    лог(`«${задача.имя}»: не разобрал «Последний запуск» (${задача.последний}) — запускаю`);
    return true;
  }

  // разбираем как московское время, иначе на UTC-сервере отметка уезжает на три часа вперёд
  const было = Date.UTC(+м[3], +м[2] - 1, +м[1], +м[4], +м[5]) - МСК_СМЕЩЕНИЕ;
  return (Date.now() - было) / 60000 >= задача.каждые;
}

async function выполнить(задача, параметры) {
  const обработчик = ОБРАБОТЧИКИ[задача.имя];
  if (!обработчик) {
    лог(`пропуск «${задача.имя}» — нет такого обработчика`);
    return;
  }

  лог(`старт «${задача.имя}»`);
  const начало = Date.now();

  try {
    const результат = await обработчик(параметры, задача);
    const секунд = Math.round((Date.now() - начало) / 1000);
    await отметитьЗапуск(задача, `${результат} | ${секунд} сек`);
    лог(`готово «${задача.имя}»: ${результат}`);
  } catch (ош) {
    const текст = String(ош.message || ош).slice(0, 400);
    await отметитьЗапуск(задача, `ОШИБКА: ${текст}`);
    лог(`ошибка «${задача.имя}»: ${текст}`);
  }
}

async function проход({ принудительно = null } = {}) {
  const { параметры, задачи } = await читатьНастройки();

  for (const задача of задачи) {
    if (принудительно) {
      if (задача.имя !== принудительно) continue;
    } else {
      if (!задача.включена) continue;
      if (!пора(задача)) continue;
    }
    await выполнить(задача, параметры);
  }
}

async function main() {
  const аргументы = process.argv.slice(2);

  // node src/index.js --task "OZON остатки" — запустить одну задачу и выйти
  const индексЗадачи = аргументы.indexOf('--task');
  if (индексЗадачи !== -1) {
    await проход({ принудительно: аргументы[индексЗадачи + 1] });
    return;
  }

  // node src/index.js --once — один проход по включённым задачам и выход
  if (аргументы.includes('--once')) {
    await проход();
    return;
  }

  лог('сервис запущен, проверка расписания раз в минуту');
  for (;;) {
    try {
      await проход();
    } catch (ош) {
      лог('сбой прохода:', String(ош.message || ош));
    }
    await сон(60000);
  }
}

main().catch((ош) => {
  лог('фатально:', ош);
  process.exit(1);
});
