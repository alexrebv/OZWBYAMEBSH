import { COLUMNS, SHEETS, TASKS } from './schemas.js';
import { обеспечитьЛист, чистить, буква } from './sheets.js';
import { читатьНастройки, отметитьЗапуск, погаситьПараметр, ПАРАМЕТР_РЕСТАРТА } from './config.js';
import { сон, МСК_СМЕЩЕНИЕ, изЯчейки } from './http.js';
import * as ozon from './ozon.js';
import * as wb from './wb.js';
import * as yandex from './yandex.js';
import * as fbo from './fbo.js';

const ОБРАБОТЧИКИ = {
  'OZON продажи': ozon.продажи,
  'OZON остатки': ozon.остатки,
  'WB продажи': wb.продажи,
  'WB остатки': wb.остатки,
  'Яндекс продажи': yandex.продажи,
  'Яндекс остатки': yandex.остатки,

  'OZON FBO продажи': fbo.ozonFboПродажи,
  'OZON FBO остатки': fbo.ozonFboОстатки,
  'WB FBO продажи': fbo.wbFboПродажи,
  'WB FBO остатки': fbo.wbFboОстатки,
  'Яндекс FBO продажи': fbo.ямFboПродажи,
  'Яндекс FBO остатки': fbo.ямFboОстатки,
};

const лог = (...ч) => console.log(new Date().toISOString(), ...ч);

// Ячейку пишем через USER_ENTERED, поэтому Sheets хранит её как дату-время и отдаёт
// обратно в своём формате отображения — ведущие нули в дне, месяце и часе не гарантированы
// («26.08.2026, 8:11:32»). Поэтому допускаем одну или две цифры везде, где Sheets их режет.
const ОТМЕТКА = /(\d{1,2})\.(\d{1,2})\.(\d{4}),?\s+(\d{1,2}):(\d{2})/;

/** Пора ли запускать: прошло ли «каждые N минут» с прошлого раза. */
function пора(задача) {
  if (!задача.последний) return true;

  const м = String(задача.последний).match(ОТМЕТКА);
  if (!м) {
    // не молчим: иначе неразобранная отметка тихо превращается в запуск каждую минуту
    лог(`«${задача.имя}»: не разобрал «Последний запуск» (${задача.последний}) — запускаю`);
    return true;
  }

  // «Последний запуск» пишется по Москве, а сервер живёт в UTC:
  // без сдвига отметка уезжает на три часа вперёд
  const было = Date.UTC(+м[3], +м[2] - 1, +м[1], +м[4], +м[5]) - МСК_СМЕЩЕНИЕ;
  return (Date.now() - было) / 60000 >= задача.каждые;
}

/**
 * Листы продаж пишутся upsert-ом: строка, однажды попавшая на лист, остаётся навсегда,
 * даже если формат изменился. Разовый сброс чистит лист и расширяет окно, чтобы
 * задача собрала его заново. Листам остатков это не нужно — они снапшоты.
 */
const ЛИСТ_ПРОДАЖ = {
  'OZON продажи': SHEETS.OZON_ПРОДАЖИ,
  'WB продажи': SHEETS.WB_ПРОДАЖИ,
  'Яндекс продажи': SHEETS.ЯМ_ПРОДАЖИ,

  // у FBO Яндекса имя задачи и имя листа не совпадают: «Яндекс FBO продажи» → «ЯМ FBO продажи»
  'OZON FBO продажи': SHEETS.OZON_FBO_ПРОДАЖИ,
  'WB FBO продажи': SHEETS.WB_FBO_ПРОДАЖИ,
  'Яндекс FBO продажи': SHEETS.ЯМ_FBO_ПРОДАЖИ,
};

/** Окно пересборки. Совпадает с ОКНО_СОЗДАНИЯ_ДНЕЙ в src/ozon.js — глубже API не отдаёт. */
const ГЛУБИНА_СБРОСА = 60;

async function сбросить(задача) {
  const лист = ЛИСТ_ПРОДАЖ[задача.имя];
  if (!лист) {
    лог(`«${задача.имя}»: сброс не нужен, лист перезаписывается целиком`);
    return;
  }

  await обеспечитьЛист(лист);
  await чистить(лист, `A2:${буква(COLUMNS[лист].length)}`);
  задача.глубина = ГЛУБИНА_СБРОСА;
  лог(`«${задача.имя}»: лист очищен, окно расширено до ${ГЛУБИНА_СБРОСА} дней`);
}

async function выполнить(задача, параметры) {
  const обработчик = ОБРАБОТЧИКИ[задача.имя];
  if (!обработчик) {
    лог(`пропуск «${задача.имя}» — нет такого обработчика`);
    return;
  }

  лог(`старт «${задача.имя}»${задача.сброс ? ' — СБРОС' : ''}`);
  const начало = Date.now();

  // «С даты» не очищается сама: пока она стоит, каждый прогон тянет весь период заново.
  // Молчать об этом нельзя — задача выглядит обычной, а грузит в разы больше.
  if (задача.сдаты) {
    лог(изЯчейки(задача.сдаты)
      ? `«${задача.имя}»: период с ${задача.сдаты}, глубина не действует — очистите «С даты» после заливки`
      : `«${задача.имя}»: «С даты» = «${задача.сдаты}» не разобрана, работаю от глубины`);
  }

  try {
    if (задача.сброс) await сбросить(задача);
    const результат = await обработчик(параметры, задача);
    const секунд = Math.round((Date.now() - начало) / 1000);
    await отметитьЗапуск(задача, `${результат} | ${секунд} сек`);
    лог(`готово «${задача.имя}»: ${результат}`);
  } catch (ош) {
    const текст = String(ош.message || ош).slice(0, 400);
    await отметитьЗапуск(задача, `ОШИБКА: ${текст}`);
    лог(`ошибка «${задача.имя}»: ${текст}`);
  }
}

/**
 * Флаг рестарта на листе настроек: единица в значении параметра «Рестарт».
 * Гасим ячейку ДО выхода — иначе сервис поднимется, снова увидит единицу
 * и уйдёт в цикл перезапусков. Если погасить не вышло, не выходим вовсе.
 */
async function пораПерезапуститься(параметры, строкиПараметров) {
  if (String(параметры[ПАРАМЕТР_РЕСТАРТА] ?? '').trim() !== '1') return false;

  const строка = строкиПараметров[ПАРАМЕТР_РЕСТАРТА];
  if (!строка) {
    лог(`«${ПАРАМЕТР_РЕСТАРТА}» = 1, но строка параметра не найдена — не перезапускаюсь`);
    return false;
  }

  try {
    await погаситьПараметр(строка);
  } catch (ош) {
    лог(`рестарт запрошен, но флаг не погасился (${String(ош.message || ош)}) — не перезапускаюсь`);
    return false;
  }

  лог('рестарт запрошен с листа настроек — выхожу, Railway поднимет сервис заново');
  return true;
}

async function проход({ принудительно = null } = {}) {
  const { параметры, строкиПараметров, задачи } = await читатьНастройки();

  if (await пораПерезапуститься(параметры, строкиПараметров)) {
    await сон(200);          // даём логу дописаться в stdout
    process.exit(0);
  }

  // строки задач отбираются по списку TASKS, поэтому опечатка в имени просто исчезает.
  // Для ручного запуска это выглядит как «ничего не произошло» — скажем прямо.
  if (принудительно && !задачи.some((з) => з.имя === принудительно)) {
    лог(`задача «${принудительно}» не найдена на листе. Известные: ${TASKS.join(', ')}`);
    return;
  }

  for (const задача of задачи) {
    if (принудительно) {
      if (задача.имя !== принудительно) continue;
    } else {
      if (!задача.включена) continue;
      if (!пора(задача)) continue;
    }
    await выполнить(задача, параметры);
  }
}

async function main() {
  const аргументы = process.argv.slice(2);

  // node src/index.js --task "OZON остатки" — запустить одну задачу и выйти
  const индексЗадачи = аргументы.indexOf('--task');
  if (индексЗадачи !== -1) {
    await проход({ принудительно: аргументы[индексЗадачи + 1] });
    return;
  }

  // node src/index.js --once — один проход по включённым задачам и выход
  if (аргументы.includes('--once')) {
    await проход();
    return;
  }

  лог('сервис запущен, проверка расписания раз в минуту');
  for (;;) {
    try {
      await проход();
    } catch (ош) {
      лог('сбой прохода:', String(ош.message || ош));
    }
    await сон(60000);
  }
}

main().catch((ош) => {
  лог('фатально:', ош);
  process.exit(1);
});
