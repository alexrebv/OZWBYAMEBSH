export async function продажи(параметры, задача) {
  const глубина = задача.глубина || 7;
  const по = new Date();
  const с = изЯчейки(задача.сдаты) || new Date(по.getTime() - глубина * 24 * 3600 * 1000);

  const задания = [];
  const сек = (д) => Math.floor(д.getTime() / 1000);

  // период режем на окна: длиннее 30 календарных дней метод отвечает
  // 400 IncorrectParameter, причём без указания, какой именно параметр не так
  for (const [а, б] of окнами(с, по, ОКНО_ДНЕЙ)) {
    let next = 0;

    for (let страниц = 0; страниц < 200; страниц += 1) {
      const url = `/api/v3/orders?limit=1000&next=${next}&dateFrom=${сек(а)}&dateTo=${сек(б)}`;
      const ответ = await вызов(параметры, url);
      const пачка = ответ.orders || [];
      задания.push(...пачка);

      if (!пачка.length || !ответ.next || ответ.next === next) break;
      next = ответ.next;
      await сон(ПАУЗА);
    }
  }

  const отметка = вТаблицу(new Date());
  const строки = задания.map((з) => строкаИзЗадания(з, отметка));
  const итог = await сохранить(SHEETS.WB_ПРОДАЖИ, строки);

  const освежено = await обновитьСтатусы(параметры);
  return `заданий ${итог.всего}, новых ${итог.новых}, статусов ${освежено}`;
}

function строкаИзЗадания(з, отметка) {
  const копейки = (в) => (Number(в) || 0) / 100;
  return [
    String(з.id),
    вТаблицу(з.createdAt),
    з.article || '-',
    з.nmId || '-',
    з.chrtId || '-',
    (з.skus || []).length ? String(з.skus[0]) : '-',
    копейки(з.price),
    копейки(з.convertedPrice ?? з.price),
    з.currencyCode || з.convertedCurrencyCode || '-',
    '-',   // статус продавца приходит отдельным методом
    '-',   // статус WB
    з.warehouseId || '-',
    з.supplyId || '-',
    ТИПЫ_ДОСТАВКИ[з.deliveryType] || з.deliveryType || '-',
    флаг(з.cargoType > 1),
    вТаблицу(изМосквы(з.ddate)),   // ddate приходит датой без времени и без пояса
    копейки(з.dprice),
    флаг(з.options?.isB2B),
    з.comment || '-',
    отметка,
  ];
}

/**
 * Метод списка отдаёт задания без актуального статуса, поэтому статусы
 * добираются отдельно — только по тем заданиям, которые ещё не закрыты.
 */
async function обновитьСтатусы(параметры, максимум = 5000) {
  const финальныеРу = new Set([...ФИНАЛЬНЫЕ].map((к) => СТАТУСЫ_WB[к]));
  const данные = await читать(SHEETS.WB_ПРОДАЖИ, 'A2:K');
  if (!данные.length) return 0;

  const кОбновлению = [];
  for (let i = данные.length - 1; i >= 0 && кОбновлению.length < максимум; i -= 1) {
    const id = данные[i][0];
    const статус = данные[i][10];
    if (id && !финальныеРу.has(статус)) кОбновлению.push({ id: Number(id), строка: i });
  }
  if (!кОбновлению.length) return 0;

  const найдено = new Map();
  for (let i = 0; i < кОбновлению.length; i += 1000) {
    const пачка = кОбновлению.slice(i, i + 1000);
    const ответ = await вызов(параметры, '/api/v3/orders/status', 'POST', {
      orders: пачка.map((э) => э.id),
    });
    for (const о of ответ.orders || []) {
      найдено.set(String(о.id), [
        СТАТУСЫ_ПРОДАВЦА[о.supplierStatus] || о.supplierStatus || '-',
        СТАТУСЫ_WB[о.wbStatus] || о.wbStatus || '-',
      ]);
    }
    await сон(ПАУЗА);
  }

  const колонки = данные.map((р) => [р[9] ?? '-', р[10] ?? '-']);
  let обновлено = 0;
  for (const э of кОбновлению) {
    const н = найдено.get(String(э.id));
    if (н) { колонки[э.строка] = н; обновлено += 1; }
  }

  const { писать } = await import('./sheets.js');
  await писать(SHEETS.WB_ПРОДАЖИ, `J2:K${колонки.length + 1}`, колонки);
  return обновлено;
}

// ─────────────────────── ОСТАТКИ ───────────────────────

/** Имя склада для шапки. Имя может не прийти — тогда показываем id. */
const подпись = (с) => с.name || String(с.id);

/** Баркоды сортируем как числа: длина у них бывает разной. */
const поПорядку = (а, б) => а.localeCompare(б, 'ru', { numeric: true });

export async function остатки(параметры) {
  const склады = await вызов(параметры, '/api/v3/warehouses');
  // дедупликация по id: дубль в ответе дал бы лишнюю колонку в матрице и завысил
  // счётчик складов в отчёте. При максимуме это было не видно, при сумме — видно
  const список = [...new Map(
    (Array.isArray(склады) ? склады : склады.warehouses || [])
      .filter((с) => с.id)
      .map((с) => [с.id, с]),
  ).values()];

  const баркоды = await штрихкодыИзСправочника();
  if (!список.length) throw new Error('У продавца не найдено складов FBS');
  if (!баркоды.length) throw new Error('В справочнике «Общая инфо» нет штрихкодов');

  // Копим «баркод → склад → количество». Ключ склада — id, а не имя: имена могут совпадать.
  //
  // В колонку «Остаток» идёт СУММА по складам — так попросил владелец.
  // Оговорка, которую надо помнить: WB позволяет объявить один и тот же физический
  // товар сразу на нескольких складах-приёмниках, и тогда сумма его задваивает.
  // Поэтому максимум продолжает считаться и попадает и в строку результата,
  // и в отдельную колонку листа «WB по складам»: по расхождению этих двух чисел
  // видно, задвоение перед нами или реальный остаток на разных складах.
  const поБаркоду = new Map();

  /** Остатки одного склада. Бросает, если хоть одна пачка не далась. */
  const собратьСклад = async (склад) => {
    for (let i = 0; i < баркоды.length; i += 1000) {
      const пачка = баркоды.slice(i, i + 1000);
      const ответ = await вызов(параметры, `/api/v3/stocks/${склад.id}`, 'POST', { skus: пачка });

      for (const о of ответ.stocks || []) {
        const кол = Number(о.amount) || 0;
        // не только ноль: отрицательное значение при сумме уменьшало бы остаток
        if (!(кол > 0)) continue;
        const баркод = String(о.sku);
        if (!поБаркоду.has(баркод)) поБаркоду.set(баркод, new Map());
        поБаркоду.get(баркод).set(склад.id, кол);
      }
      await сон(ПАУЗА);
    }
  };

  // Складов под два десятка, и раньше сбой на любом хоронил весь прогон вместе
  // с уже собранными данными. Теперь неудавшиеся откладываем и проходим по ним
  // ещё раз: сетевая икота на одном складе больше не стоит целого часа.
  const неудачные = [];
  for (const склад of список) {
    try {
      await собратьСклад(склад);
    } catch (ош) {
      неудачные.push({ склад, причина: String(ош.message || ош) });
    }
  }

  for (let i = неудачные.length - 1; i >= 0; i -= 1) {
    try {
      await собратьСклад(неудачные[i].склад);
      неудачные.splice(i, 1);
    } catch (ош) {
      неудачные[i].причина = String(ош.message || ош);
    }
  }

  // Остаток без части складов занижен, а лист снапшотный: записав такое, мы затрём
  // исправный прошлый снимок неверными числами. Лучше упасть и сохранить его.
  if (неудачные.length) {
    const кто = неудачные.map((н) => подпись(н.склад)).join(', ');
    throw new Error(`не собраны остатки по складам: ${кто}. Лист не тронут. ${неудачные[0].причина}`);
  }

  const отметка = вТаблицу(new Date());
  const сОстатком = [...поБаркоду.keys()].sort(поПорядку);

  let вРасчёт = 0;
  let максимумом = 0;
  const строки = сОстатком.map((баркод) => {
    const поСкладам = поБаркоду.get(баркод);
    const количества = [...поСкладам.values()];
    const сумма = количества.reduce((а, б) => а + б, 0);
    вРасчёт += сумма;
    максимумом += Math.max(...количества);
    return [баркод, сумма, поСкладам.size, отметка];
  });

  await сохранить(SHEETS.WB_ОСТАТКИ, строки);
  await записатьПоСкладам(список, поБаркоду, сОстатком);

  // обе цифры в результате: если сумма сильно выше максимума, товар объявлен
  // на нескольких складах, и «Остаток» задваивается
  return `складов ${список.length}, баркодов ${поБаркоду.size}, `
    + `в расчёт ${вРасчёт} (максимумом было бы ${максимумом})`;
}

/**
 * Матрица «баркод × склад» — справочный лист, по нему видно, где WB задваивает
 * один и тот же товар. Шапка динамическая (состав складов меняется), поэтому лист
 * пишется напрямую, а не через сохранить: там ширина берётся из статической схемы.
 */
async function записатьПоСкладам(список, поБаркоду, сОстатком) {
  const склады = [...список].sort((а, б) => подпись(а).localeCompare(подпись(б), 'ru'));
  // «Максимум» дописан в конец, а не вставлен рядом с суммой: так позиции всех
  // прежних колонок сервиса остаются на местах. Но лист стал на колонку шире,
  // поэтому держать что-то своё справа от «Складов» на этом листе больше нельзя
  const шапка = ['Штрихкод', ...склады.map(подпись), 'В расчёт (сумма)', 'Складов', 'Максимум'];

  const строки = сОстатком.map((баркод) => {
    const поСкладам = поБаркоду.get(баркод);
    const количества = [...поСкладам.values()];
    return [
      баркод,
      // склада нет у баркода — пишем 0, а не пустоту, иначе колонка не суммируется
      ...склады.map((с) => поСкладам.get(с.id) || 0),
      количества.reduce((а, б) => а + б, 0),
      поСкладам.size,
      Math.max(...количества),
    ];
  });

  await обеспечитьЛист(SHEETS.WB_СКЛАДЫ);

  // складов могло стать меньше — чистим ещё и по прошлой ширине,
  // иначе от прошлого прогона останется хвост колонок со старыми числами
  const прошлая = (await читать(SHEETS.WB_СКЛАДЫ, '1:1'))[0]?.length || 0;
  await чистить(SHEETS.WB_СКЛАДЫ, `A1:${буква(Math.max(шапка.length, прошлая))}`);

  const конец = буква(шапка.length);
  await писать(SHEETS.WB_СКЛАДЫ, `A1:${конец}1`, [шапка]);
  if (строки.length) {
    await писать(SHEETS.WB_СКЛАДЫ, `A2:${конец}${строки.length + 1}`, строки);
  }
}
