import { SHEETS, TASKS } from './schemas.js';
import { читать, писать } from './sheets.js';

/**
 * Лист «Настройки» устроен так:
 *
 *   A2:C..   блок параметров:  Параметр | Значение | Комментарий
 *   A21:G..  блок задач:       Задача | Вкл | Каждые, мин | Глубина, дней | Последний запуск | Результат | С даты
 *
 * Между блоками на листе живут посторонние таблицы (например «Группы: держим дольше»),
 * поэтому строки отбираются по списку TASKS, а не по одному лишь диапазону.
 *
 * Включение задачи — цифра 1 в колонке «Вкл». Пусто или 0 — выключено.
 */

const ПАРАМЕТРЫ_ОТ = 2;
const ПАРАМЕТРЫ_ДО = 18;
const ЗАДАЧИ_ОТ = 21;
const ЗАДАЧИ_ДО = 80;

/** Что написать в «Последний запуск», чтобы задача разово пересобрала свой лист. */
const СЛОВО_СБРОСА = 'сброс';

/** Переменная окружения перебивает значение из таблицы: ключи лучше держать в Railway. */
const ИЗ_ОКРУЖЕНИЯ = {
  'OZON Client-Id': 'OZON_CLIENT_ID',
  'OZON Api-Key': 'OZON_API_KEY',
  'WB Api-Key': 'WB_API_KEY',
  'Яндекс Api-Key': 'YM_API_KEY',
  'Яндекс campaignId': 'YM_CAMPAIGN_ID',
  // FBY и FBS у Яндекса — разные магазины с разными campaignId.
  // Подставить сюда FBS-кампанию нельзя: метод вернёт пустой список без ошибки.
  'Яндекс campaignId FBY': 'YM_CAMPAIGN_ID_FBY',
};

export async function читатьНастройки() {
  const параметры = {};
  const строкиП = await читать(SHEETS.НАСТРОЙКИ, `A${ПАРАМЕТРЫ_ОТ}:B${ПАРАМЕТРЫ_ДО}`);

  for (const [имя, значение] of строкиП) {
    if (!имя) continue;
    параметры[String(имя).trim()] = значение === undefined ? '' : String(значение).trim();
  }

  for (const [имя, пер] of Object.entries(ИЗ_ОКРУЖЕНИЯ)) {
    if (process.env[пер]) параметры[имя] = process.env[пер].trim();
  }

  const задачи = [];
  const строкиЗ = await читать(SHEETS.НАСТРОЙКИ, `A${ЗАДАЧИ_ОТ}:G${ЗАДАЧИ_ДО}`);

  строкиЗ.forEach((р, i) => {
    // индекс i считается по всему прочитанному диапазону, поэтому «строка» остаётся верной,
    // даже когда посторонние строки отсеиваются
    const имя = String(р[0] ?? '').trim();
    if (!TASKS.includes(имя)) return;

    // «сброс» вместо отметки времени — разовая полная пересборка листа задачи.
    // Прогон затирает ячейку своим результатом, поэтому сброс срабатывает ровно один раз.
    const отметка = р[4] ? String(р[4]).trim() : '';
    const сброс = отметка.toLowerCase() === СЛОВО_СБРОСА;

    задачи.push({
      имя,
      включена: String(р[1] ?? '').trim() === '1',
      каждые: Number(р[2]) || 60,
      глубина: Number(р[3]) || 0,
      // «С даты» перебивает глубину: глубина привязана к «сегодня» и через неделю
      // даст другой период, а явная дата — нет. Нужна для разовой перезаливки.
      сдаты: р[6] === undefined || р[6] === null ? '' : String(р[6]).trim(),
      сброс,
      последний: сброс ? '' : отметка,
      строка: ЗАДАЧИ_ОТ + i,
    });
  });

  return { параметры, задачи };
}

/** Пишет в строку задачи время запуска и результат. Колонки E и F. */
export async function отметитьЗапуск(задача, результат) {
  const когда = new Date().toLocaleString('ru-RU', { timeZone: 'Europe/Moscow' });
  await писать(SHEETS.НАСТРОЙКИ, `E${задача.строка}:F${задача.строка}`, [[когда, результат]]);
}

export function требовать(параметры, ...имена) {
  const нет = имена.filter((и) => !параметры[и]);
  if (нет.length) {
    throw new Error(`Не заполнено в настройках: ${нет.join(', ')}`);
  }
  return имена.map((и) => параметры[и]);
}
